// 仅描述已核对的鼠标命令。上层必须先检查能力，不能给未知 PID 套用默认写入协议。
type mouseCapability struct {
	MaxDPI        int   // >0 才支持04/85读取及04/05写入16位XY DPI；合法范围100..MaxDPI。
	DPITID        byte  // DPI读取和写入均使用此TID；写入storage固定1，与上游实际报文一致。
	DPILegacyRead bool  // 只表示04/85的arguments[0]=1；false为0。不是旧版单字节DPI。
	PollTID       byte  // 回报率读取的TID，不一定等于写入TID。
	PollWriteTID  byte  // 旧协议的唯一写入、或新协议第一次写入的TID。
	PollSecondTID byte  // PollDualWrite时第二次写入的TID。
	PollV2        bool  // false:00/85读、00/05写；true:00/C0读、00/40写。
	PollDualWrite bool  // 顺序发送00/40，arguments[0]先0后1；每一步都必须检查响应。
	PollRates     []int // nil表示禁用回报率读写；非nil时只允许列出的Hz值。
}

